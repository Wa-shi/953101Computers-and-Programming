public class Exercise1 {
    public static void main(String[] args) {
        // Step 1: เริ่มต้น loop โดยให้ i = 1
        // Step 2: ตรวจสอบเงื่อนไข i <= 4 ถ้าเป็นจริงจะเข้าทำงานใน loop
        // Step 3: ทำงานจบ 1 รอบ จะสั่ง i++ (เพิ่มค่า i ทีละ 1)
        for (int i = 1; i <= 4; i++) {
            System.out.println(i + " squared = " + (i * i));
            }
        System.out.println("Done");
        }
}